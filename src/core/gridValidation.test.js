import assert from "node:assert/strict";
import test from "node:test";

import { validateScaledTemplateSource, validateTemplateRows } from "./gridValidation.js";

test("16×16 그림 도안 검증은 잘못된 행 길이를 거부한다", () => {
  assert.throws(
    () =>
      validateTemplateRows("깨진 도안", [
        "................",
        "...............",
        "................",
        "................",
        "................",
        "................",
        "................",
        "................",
        "................",
        "................",
        "................",
        "................",
        "................",
        "................",
        "................",
        "................",
      ]),
    /열 개수/,
  );
});

test("8×8 보석 템플릿 검증은 trailing background로 길어진 행을 거부한다", () => {
  assert.throws(
    () =>
      validateScaledTemplateSource(
        "공룡",
        `
....11..
...1221.
..122221
.1222221
12222311
122221...
.1111...
..3.3...
`,
        {
          "1": "#a7f070",
          "2": "#38b764",
          "3": "#8f563b",
        },
      ),
    /열 개수/,
  );
});

test("8×8 보석 템플릿 검증은 팔레트에 없는 문자를 거부한다", () => {
  assert.throws(
    () =>
      validateScaledTemplateSource(
        "누락 문자",
        `
....11..
...1221.
..12x221
.1222221
12222311
122221..
.1111...
..3.3...
`,
        {
          "1": "#a7f070",
          "2": "#38b764",
          "3": "#8f563b",
        },
      ),
    /허용되지 않은 문자/,
  );
});

test("16×16 보석 템플릿 검증은 옵션 크기를 그대로 반환한다", () => {
  const result = validateScaledTemplateSource(
    "해님",
    `
................
.......1........
....1..1..1.....
.....122221.....
...1122222211...
...1222222221...
.11122222222111.
..122222222221..
..122222222221..
.11122222222111.
...1222222221...
...1122222211...
.....122221.....
....1..1..1.....
.......1........
................
`,
    {
      "1": "#ffcd75",
      "2": "#ef7d57",
    },
    {
      expectedWidth: 16,
      expectedHeight: 16,
      label: "보석 템플릿 원본",
    },
  );

  assert.equal(result.width, 16);
  assert.equal(result.height, 16);
  assert.equal(result.rows.length, 16);
  assert.equal(result.rows[0].length, 16);
});
