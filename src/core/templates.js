// 내장 색칠 도안 (16×16 라인아트, 자작 — 저작권 문제 없음).
// 문자 → 밝기: '.' = 255(종이), '#' = 45(윤곽선). 그리드 크기(16/32/64)는
// 모두 16의 배수이므로 정수 배율 확대로 참조 배열을 만든다.

const CHAR_LUM = { ".": 255, "#": 45 };
function pixelTemplate(name, rows) {
  const doubledRows = rows.map((row) => [...row].map((cell) => cell.repeat(2)).join(""));
  return {
    name,
    rows: doubledRows.flatMap((row) => [row, row]),
  };
}

