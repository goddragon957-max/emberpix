// 도안 → 참조 배열 (size×size, 밝기 0~255).
export function templateToReference(tpl, size) {
  const n = tpl.rows.length; // 16
  const scale = size / n;
  const out = new Array(size * size).fill(255);
  for (let y = 0; y < n; y++) {
    for (let x = 0; x < n; x++) {
      const v = CHAR_LUM[tpl.rows[y][x]] ?? 255;
      if (v === 255) continue;
      for (let dy = 0; dy < scale; dy++) {
        for (let dx = 0; dx < scale; dx++) {
          out[(y * scale + dy) * size + (x * scale + dx)] = v;
        }
      }
    }
  }
  return out;
}
